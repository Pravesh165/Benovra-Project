CREATE TABLE benefit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    per_claim_limit NUMERIC(12, 2) NOT NULL,
    coverage_window_days INTEGER NOT NULL,
    active BOOLEAN NOT NULL
);

CREATE TABLE card_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_member_id VARCHAR(60) NOT NULL,
    card_product VARCHAR(60) NOT NULL,
    merchant_name VARCHAR(160) NOT NULL,
    merchant_category VARCHAR(80),
    amount NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    purchase_date DATE NOT NULL,
    description VARCHAR(500),
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE entitlement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_product VARCHAR(60) NOT NULL,
    benefit_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL,
    CONSTRAINT uk_entitlement_card_product_benefit UNIQUE (card_product, benefit_id),
    CONSTRAINT fk_entitlement_benefit FOREIGN KEY (benefit_id) REFERENCES benefit (id)
);

CREATE TABLE claim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    benefit_id BIGINT NOT NULL,
    claim_amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    decision_reason VARCHAR(500),
    payout_reference VARCHAR(60),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE,
    decided_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_claim_transaction_benefit UNIQUE (transaction_id, benefit_id),
    CONSTRAINT fk_claim_transaction FOREIGN KEY (transaction_id) REFERENCES card_transaction (id),
    CONSTRAINT fk_claim_benefit FOREIGN KEY (benefit_id) REFERENCES benefit (id)
);

CREATE TABLE claim_prefilled_data (
    claim_id BIGINT NOT NULL,
    field_key VARCHAR(60) NOT NULL,
    field_value VARCHAR(500),
    PRIMARY KEY (claim_id, field_key),
    CONSTRAINT fk_claim_prefilled_data_claim FOREIGN KEY (claim_id) REFERENCES claim (id)
);

CREATE TABLE claim_audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL,
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    actor VARCHAR(40) NOT NULL,
    detail VARCHAR(500),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_claim_audit_event_claim FOREIGN KEY (claim_id) REFERENCES claim (id)
);

CREATE TABLE claim_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL,
    document_type VARCHAR(40) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    size_bytes BIGINT NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    required_flag BOOLEAN NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_claim_document_claim FOREIGN KEY (claim_id) REFERENCES claim (id)
);

CREATE INDEX idx_transaction_member_created ON card_transaction (card_member_id, created_at);
CREATE INDEX idx_transaction_status_created ON card_transaction (status, created_at);
CREATE INDEX idx_entitlement_product_active ON entitlement (card_product, active);
CREATE INDEX idx_claim_status_created ON claim (status, created_at);
CREATE INDEX idx_claim_audit_claim_time ON claim_audit_event (claim_id, occurred_at, id);
CREATE INDEX idx_claim_audit_actor_status ON claim_audit_event (actor, to_status);
CREATE INDEX idx_claim_document_claim_time ON claim_document (claim_id, uploaded_at, id);
